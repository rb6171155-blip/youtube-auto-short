"""
日本語TTS発音補正およびプロソディ・ブレス制御モジュール (Pronunciation & Prosody Module)

【設計方針】
1. themes.py のナレーション原稿（Single Source of Truth / 画面字幕表示用）は自然な漢字表記のまま維持する。
2. 字幕表示用テキストとTTS音声読み上げ用テキストを完全に分離する。
3. 発音補正（単語の誤読防止）とプロソディ補正（自然なブレス・読点制御）を別々の処理として管理し、個別調整を可能にする。
4. プロソディ補正では機械的な全助詞への読点挿入を禁止し、意味のまとまり・呼気段落に応じた自然な位置のみに限定する。
"""

import re

# ==============================================================================
# 1. 発音補正ルール（単語・フレーズ単位での誤読防止）
# 形式: (検索パターン[正規表現/文字列], 読み上げ用置換文字列, 補足説明)
# ==============================================================================
PRONUNCIATION_RULES = [
    # 「〜たい方へ」（動詞希望形 + 方へ）の誤読防止（ほうへ -> かたへ）
    (r"整えたい方へ", "整えたいかたへ", "theme_6_2: 整えたい方へ -> ととのえたいかたへ"),
    (r"歩きたい方へ", "歩きたいかたへ", "歩きたい方へ -> あるきたいかたへ"),
    (r"知りたい方へ", "知りたいかたへ", "知りたい方へ -> しりたいかたへ"),
    (r"相談したい方へ", "相談したいかたへ", "相談したい方へ -> そうだんしたいかたへ"),
    (r"暮らせる方へ", "暮らせるかたへ", "暮らせる方へ -> くらせるかたへ"),
]

def apply_pronunciation_dict(text: str) -> str:
    """
    ナレーション原文に対して発音補正ルールを適用し、誤読を防止したテキストを返す。
    （字幕表示用テキストには影響を与えない）
    """
    if not text:
        return ""
    
    corrected = text
    for rule in PRONUNCIATION_RULES:
        pattern, replacement = rule[0], rule[1]
        corrected = re.sub(pattern, replacement, corrected)
    
    return corrected

# ==============================================================================
# 2. プロソディ・ブレス制御ルール（自然な文節・息継ぎのための読点配置）
# 形式: (検索パターン[正規表現], 置換文字列, 補足説明)
# ==============================================================================
PROSODY_RULES = [
    # 1. 施設名・主語の提示（西田医院では -> 西田医院では、）
    (r"(西田医院では)(?!、)", r"\1、", "施設名の提示後に自然なブレス"),
    
    # 2. フック・導入部の目的格（姿勢を -> 姿勢を、）
    (r"(姿勢を)(?!、)", r"\1、", "導入部の重要名詞句後にブレス"),
    
    # 3. 手段・道具・利用節（〜を利用した -> 〜を利用した、）
    (r"([をに]利用した)(?!、)", r"\1、", "手段・方法節の区切り"),
    
    # 4. 目的・希望節（〜よう -> 〜よう、 / 〜ため -> 〜ため、）
    (r"([るい]よう)(?!、)", r"\1、", "目的節の区切り"),
    (r"([るいた]ため)(?!、)", r"\1、", "理由・目的節の区切り"),
    
    # 5. 副詞・条件節（実は〜に -> 実は〜に、）
    (r"(実は[^、。!?！？]+?に)(?!、)", r"\1、", "問いかけ・逆接の区切り"),
    
    # 6. 案内・CTA導入部（詳しくは -> 詳しくは、 / 取り組みは -> 取り組みは、）
    (r"(詳しくは)(?!、)", r"\1、", "CTA導入部のブレス"),
    (r"(取り組みは)(?!、)", r"\1、", "CTA導入部のブレス"),
    (r"(詳細は)(?!、)", r"\1、", "CTA導入部のブレス"),
]

def format_spoken_prosody(text: str) -> str:
    """
    TTS読み上げ用テキストに対して、人間らしい自然な文節・ブレス（息継ぎ）を与える読点を配置する。
    機械的な過剰読点を防ぎ、重複読点や句点前の不正読点を自動整形する。
    """
    if not text:
        return ""
    
    result = text
    for rule in PROSODY_RULES:
        pattern, replacement = rule[0], rule[1]
        result = re.sub(pattern, replacement, result)
    
    # 連続読点（例: 、、）を単一読点へ正規化
    result = re.sub(r"、+", "、", result)
    
    # 句点・感嘆符・疑問符直前の不要な読点を除去（例: 、。 -> 。）
    result = re.sub(r"、([。！？!?])", r"\1", result)
    
    return result

# ==============================================================================
# 3. 統合変換処理（ナレーション原稿 -> TTS読み上げ専用テキスト）
# ==============================================================================
def get_spoken_text(text: str) -> str:
    """
    ナレーション原稿（字幕用マスター）から、
    1. 発音補正
    2. プロソディ・ブレス補正
    を順次適用し、edge-tts 読み上げ専用の Spoken Text を生成する。
    """
    if not text:
        return ""
    
    # ステップ1: 発音補正
    pron_corrected = apply_pronunciation_dict(text)
    
    # ステップ2: プロソディ・ブレス補正
    spoken_text = format_spoken_prosody(pron_corrected)
    
    return spoken_text

if __name__ == '__main__':
    sample_text = "ふらつきやすい姿勢を整えたい方へ。自分の体重を利用したレッドコードで、体の奥の筋肉を刺激します。西田医院の取り組みはプロフィールから。"
    print("=== Pronunciation & Prosody Module Test ===")
    print("Master Text (字幕用):  ", sample_text)
    print("Pronunciation Corrected:", apply_pronunciation_dict(sample_text))
    print("Spoken Text (TTS用):   ", get_spoken_text(sample_text))
